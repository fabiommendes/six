"""Track which manual text depends on which rules text.

Every consumer (a chapter or a chapter section) declares its sources in
`fonte:`. `fontes.lock.yaml` records, per consumer and source, the
fingerprint of the source text when a person last reviewed the manual text
against it, plus the commit it was reviewed at. `check` compares fingerprints
with the current regras/ text; `mark` records a review.
"""

import difflib
from dataclasses import dataclass

import yaml

from . import chapters, markers, paths
from .markdown_sections import sections, split_frontmatter
from .sources import SourceError, SourceRef, head_commit, is_committed

LOCK_HEADER = """\
# Generated by `python -m rulebook sync-mark`; do not edit by hand.
# For each manual consumer (chapter or section) and each regras/
# source it declares in `fonte:`, the fingerprint of the source text when the
# manual text was last reviewed against it, and the commit of that review.
"""


@dataclass
class Status:
    consumer: str
    ref: SourceRef
    state: str  # ok | changed | new | broken
    detail: str = ""


def consumers() -> list[tuple[str, list[SourceRef]]]:
    found = []
    for chapter in chapters.load_all(include_drafts=True):
        found += chapter.consumers()
    return found


def load_lock() -> dict:
    if not paths.LOCK_FILE.exists():
        return {}
    return yaml.safe_load(paths.LOCK_FILE.read_text(encoding="utf-8")) or {}


def save_lock(lock: dict) -> None:
    ordered = {key: dict(sorted(lock[key].items())) for key in sorted(lock)}
    text = yaml.safe_dump(ordered, allow_unicode=True, sort_keys=False, width=100)
    paths.LOCK_FILE.write_text(LOCK_HEADER + text, encoding="utf-8")


def statuses() -> tuple[list[Status], list[str]]:
    """(status per declared source, lock entries no longer declared)."""
    lock = load_lock()
    result, declared = [], set()
    for consumer, refs in consumers():
        for ref in refs:
            declared.add((consumer, str(ref)))
            entry = (lock.get(consumer) or {}).get(str(ref))
            try:
                current = ref.fingerprint()
            except SourceError as error:
                result.append(Status(consumer, ref, "broken", str(error)))
                continue
            if entry is None:
                result.append(Status(consumer, ref, "new", "never reviewed"))
            elif entry["hash"] != current:
                since = entry.get("commit") or "an uncommitted version"
                result.append(Status(consumer, ref, "changed", f"changed since {since}"))
            else:
                result.append(Status(consumer, ref, "ok"))
    orphans = [
        f"{consumer} <- {ref}"
        for consumer, refs in lock.items()
        for ref in refs
        if (consumer, ref) not in declared
    ]
    return result, orphans


def diff(status: Status) -> str:
    entry = (load_lock().get(status.consumer) or {}).get(str(status.ref)) or {}
    commit = entry.get("commit")
    old = status.ref.text_at(commit) if commit else None
    if old is None:
        return "    (no recorded commit to diff against)\n"
    lines = difflib.unified_diff(
        old.splitlines(),
        status.ref.text().splitlines(),
        fromfile=f"{status.ref} @ {commit}",
        tofile=f"{status.ref} (now)",
        lineterm="",
    )
    return "".join(f"    {line}\n" for line in lines)


def proposals(result: list[Status]) -> list[Status]:
    """Sources that carry a `Proposta` note: rules approved only for testing."""
    found = []
    for status in result:
        if status.state == "broken":
            continue
        try:
            labels = markers.notes(status.ref.text())
        except SourceError:
            continue
        if "Proposta" in labels:
            found.append(status)
    return found


def check(show_diff: bool = False) -> int:
    result, orphans = statuses()
    pending = [s for s in result if s.state != "ok"]
    for status in pending:
        print(f"{status.state.upper():8} {status.consumer}\n         <- {status.ref}: {status.detail}")
        if show_diff and status.state == "changed":
            print(diff(status), end="")
    for orphan in orphans:
        print(f"UNUSED   {orphan} (dropped at the next sync-mark)")
    for status in proposals(result):
        print(f"PROPOSTA {status.consumer}\n         <- {status.ref}: approved only for testing; check the manual says so")
    ok = len(result) - len(pending)
    print(f"\n{ok}/{len(result)} sources in sync.", end=" ")
    if pending:
        print("Review the manual text above, then run `python -m rulebook sync-mark <consumer>`.")
        return 1
    print("Nothing to review.")
    return 0


def mark(targets: list[str], everything: bool = False) -> int:
    targets = [t.removeprefix("manual/") for t in targets]
    lock = load_lock()
    head = head_commit()
    marked, errors = 0, 0
    declared = dict(consumers())
    for consumer, refs in declared.items():
        base = consumer.split("#")[0]
        if not everything and not any(t in (consumer, base) for t in targets):
            continue
        entries = {}
        for ref in refs:
            try:
                fingerprint = ref.fingerprint()
            except SourceError as error:
                print(f"ERROR    {consumer}: {error}")
                errors += 1
                continue
            commit = head if is_committed(ref.path) else None
            if commit is None:
                print(f"note     {ref.path} has uncommitted changes; recorded without a commit")
            entries[str(ref)] = {"hash": fingerprint, "commit": commit}
        lock[consumer] = entries
        marked += 1
        print(f"marked   {consumer}")
    for consumer in [c for c in lock if c not in declared]:
        del lock[consumer]
    if not marked:
        print("Nothing matched. Targets are consumer ids as printed by sync-check.")
        return 1
    save_lock(lock)
    return 1 if errors else 0


def coverage() -> int:
    """List regras/ sections that no manual text is based on (informational)."""
    texts = []
    for _, refs in consumers():
        for ref in refs:
            try:
                texts.append((ref.path, ref.text()))
            except SourceError:
                pass
    uncovered = []
    for file in sorted(paths.REGRAS.rglob("*.md")):
        if file.name in ("README.md", "GLOSSARY.md"):
            continue
        rel = paths.repo_relative(file)
        _, body = split_frontmatter(file.read_text(encoding="utf-8"))
        for slug, section in sections(body).items():
            if section.level != 2:
                continue
            if not any(path == rel and section.text in text for path, text in texts):
                uncovered.append(f"{rel}#{slug}")
    for ref in uncovered:
        print(f"not used {ref}")
    print(f"\n{len(uncovered)} regras/ sections are not a source of any manual text.")
    return 0
